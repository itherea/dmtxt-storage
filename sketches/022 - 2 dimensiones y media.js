// === versión 1 ===
solid()
	.layer(shape(2, .1)
		.luma()
		.repeat(10, 10)
		.luma())
	.layer(shape(2, .1)
		.luma()
		.repeat(10, 10)
		.rotate(1)
		.luma())
	.layer(shape(100)
		.scale(1.5, .6)
		.luma()
		.diff(gradient()
			.hue())
		.luma()
		.modulate(voronoi(1000, 1, 1)))
	.hue(.1)
	.blend(noise(1, 1), .51)
	.diff(voronoi(1000,1))
	.blend(noise(100, .1), .1)
.modulatePixelate(o0,200,200,100,10)
	.out(o0)

setResolution(1600,900)

