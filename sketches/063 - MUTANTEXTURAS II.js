solid(0, 0, .15)
	.layer(shape(2, .5)
		.color(0, .75, 1)
		.scrollY(-.24)
		.luma())
	.layer(shape(100, .75)
		.scale(1, .56)
		.color(1.2, .75, 0)
		.scrollY(-.97)
		.luma())
	.blend(shape(2)
		.scrollY(1)
		.luma(), .20)
	.blend(shape(100, .75)
		.scale(1, .56)
		.color(1, .75, 0)
		.scrollY(-.97)
		.luma()
		.mask(shape(2, .51)
			.scrollY(1.756)
			.luma()))
	.saturate(3.0)
	.contrast(1.1)
	.brightness(.001)
	.add(noise(2.5), .1)
	.out(o0)

src(o0)
	.blend(osc(50, .001, .1)
		.rotate(1, .01)
		.blend(o1)
		.blend(o1)
		.modulateHue(o1, 100), -.95)
	.blend(o0, .01)
	.mult(shape(4, .5, 0)
		.scale(2.5, .5).luma())
	.out(o1)

render(o1)


screencap()

